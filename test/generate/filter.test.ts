import { describe, expect, it } from "vitest"
import type { TurnEvent } from "../../src/capture/event.ts"
import type { Change } from "../../src/capture/git.ts"
import { filterTurn } from "../../src/generate/filter.ts"
import { makeRepo } from "../helpers.ts"

const patch = (path: string, added: string[], extraHunks: string[][] = []) =>
  [
    `diff --git a/${path} b/${path}`,
    `--- a/${path}`,
    `+++ b/${path}`,
    ...[added, ...extraHunks].flatMap((lines, i) => [
      `@@ -${i * 10 + 1},0 +${i * 10 + 1},${lines.length} @@`,
      ...lines.map((l) => `+${l}`),
    ]),
    "",
  ].join("\n")

function event(
  worktree: string,
  changes: Change[],
  prompt = "do it",
  messages: string[] = ["done"],
): TurnEvent {
  return {
    schema: "ownship.turn/1",
    agent: { name: "codex", version: "0.156.1" },
    reader: { id: "codex", version: 1, source: "x", offset: 0 },
    sessionId: "s",
    turnId: "t",
    origin: "interactive",
    ts: { start: "", end: "" },
    status: "completed",
    prompt,
    messages,
    repo: {
      worktree,
      commonDir: `${worktree}/.git`,
      slug: "r-00000000",
      branch: "main",
      base: "",
      head: "",
    },
    changes,
    merged: false,
  }
}
const change = (path: string, p: string): Change => ({ path, op: "modify", patch: p })

describe("filterTurn", () => {
  it("drops lockfiles and generated files", async () => {
    const repo = makeRepo()
    const out = await filterTurn(
      event(repo, [
        change("pnpm-lock.yaml", patch("pnpm-lock.yaml", ["x"])),
        change("web/app.min.js", patch("web/app.min.js", ["x"])),
        change("api/schema.ts", patch("api/schema.ts", ["// @generated by codegen", "x"])),
        change("app/models.py", patch("app/models.py", ["class A: pass"])),
      ]),
    )
    expect(out.changes.map((c) => c.path)).toEqual(["app/models.py"])
    expect(out.dropped).toEqual([
      { path: "pnpm-lock.yaml", reason: "lockfile" },
      { path: "web/app.min.js", reason: "generated" },
      { path: "api/schema.ts", reason: "generated" },
    ])
  })

  it("honors .ownshipignore", async () => {
    const repo = makeRepo({ ".ownshipignore": "fixtures/\n" })
    const out = await filterTurn(
      event(repo, [
        change("fixtures/big.json", patch("fixtures/big.json", ["{}"])),
        change("a.py", patch("a.py", ["x"])),
      ]),
    )
    expect(out.changes.map((c) => c.path)).toEqual(["a.py"])
    expect(out.dropped).toEqual([{ path: "fixtures/big.json", reason: "ignored" }])
  })

  it("removes a hunk with an AWS key and keeps the rest of the file", async () => {
    const repo = makeRepo()
    const p = patch(
      "settings.py",
      [`AWS_KEY = "${"AKIA"}${"ABCDEFGHIJKLMNOP"}"`],
      [["DEBUG = False"]],
    )
    const out = await filterTurn(event(repo, [change("settings.py", p)]))
    expect(out.changes).toHaveLength(1)
    expect(out.changes[0]?.patch).not.toContain("AKIA")
    expect(out.changes[0]?.patch).toContain("DEBUG = False")
  })

  it("removes a prompt line with a GitHub token", async () => {
    const repo = makeRepo()
    const token = `ghp_${"a".repeat(36)}`
    const out = await filterTurn(
      event(repo, [], `use this\nGITHUB=${token}\nthanks`, [`saved ${token}`, "ok"]),
    )
    expect(out.prompt).toBe("use this\nthanks")
    expect(out.messages).toEqual(["ok"])
  })

  it("keeps a turn of 3,000 small files within the budget by omitting files", async () => {
    const repo = makeRepo()
    const changes = Array.from({ length: 3000 }, (_, i) =>
      change(
        `vendor/lib${i}.js`,
        patch(`vendor/lib${i}.js`, [`export const value${i} = ${i} // padding padding`]),
      ),
    )
    const out = await filterTurn(event(repo, changes))
    expect(out.changes.reduce((sum, c) => sum + c.patch.length, 0)).toBeLessThanOrEqual(60_000)
    expect(out.omitted).toBeGreaterThan(0)
    expect(out.changes.length + out.omitted).toBe(3000)
    expect(out.truncated).toBe(true)
  })

  it("caps a huge prompt and huge messages", async () => {
    const repo = makeRepo()
    const out = await filterTurn(event(repo, [], "x".repeat(100_000), ["y".repeat(100_000)]))
    expect(out.prompt.length).toBeLessThanOrEqual(10_100)
    expect(out.messages.join("").length).toBeLessThanOrEqual(10_100)
  })

  it("truncates a 5,000-line diff to the budget and sets truncated", async () => {
    const repo = makeRepo()
    const lines = Array.from(
      { length: 5000 },
      (_, i) => `value_${i} = compute(${i}, "padding padding")`,
    )
    const out = await filterTurn(
      event(repo, [
        change("big.py", patch("big.py", lines)),
        change("small.py", patch("small.py", ["x = 1"])),
      ]),
    )
    const total = out.changes.reduce((sum, c) => sum + c.patch.length, 0)
    expect(total).toBeLessThanOrEqual(60_000)
    expect(out.truncated).toBe(true)
    expect(out.changes.find((c) => c.path === "big.py")?.patch).toContain("[truncated by ownship]")
    expect(out.changes.find((c) => c.path === "small.py")?.patch).toContain("x = 1")
  })
})
